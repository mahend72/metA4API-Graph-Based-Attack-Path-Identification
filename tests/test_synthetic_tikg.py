def test_loader_returns_pipeline_objects(on_disk):
    ds = load_dataset("synthetic", profile="dev", root=on_disk)
    assert isinstance(ds, Dataset) and ds.is_synthetic
    assert ds.tikg.n == 350 and len(ds.tikg.triplets) == 1091
    assert ds.labels.labelled.all() and ds.labels.K == 108
    assert len(ds.reference_paths) == 76
    assert ds.severity_known.sum() == 210 and ds.severity.max() <= 1.0
    assert "NOT FOR REPORTED RESULTS" in ds.banner()
    with pytest.raises(SyntheticDataError):
        ds.require_real()


def test_loader_refuses_unflagged_directory(on_disk, tmp_path):
    import shutil
    shutil.copytree(on_disk / "dev", tmp_path / "dev")
    meta = json.loads((tmp_path / "dev" / "metadata.json").read_text())
    meta["not_for_reported_experimental_results"] = False
    (tmp_path / "dev" / "metadata.json").write_text(json.dumps(meta))
    with pytest.raises(SyntheticDataError):
        load_dataset("synthetic", profile="dev", root=tmp_path)


def test_real_branch_uses_same_interface(on_disk, tmp_path):
    syn = load_dataset("synthetic", profile="dev", root=on_disk)
    syn.tikg.save(tmp_path / "tikg.json")                       # stand-in for a real file in the native format
    lab = json.loads((on_disk / "dev" / "labels.json").read_text())
    (tmp_path / "labels.json").write_text(json.dumps(lab))
    real = load_dataset("real", tikg_path=tmp_path / "tikg.json", labels_path=tmp_path / "labels.json", name="x")
    assert isinstance(real, Dataset) and not real.is_synthetic
    assert real.require_real() is real
    with pytest.raises(FileNotFoundError):
        load_dataset("synthetic", profile="nope", root=on_disk)


def test_group_cv_is_campaign_isolated(on_disk):
    ds = load_dataset("synthetic", profile="dev", root=on_disk)
    camp = ds.tikg.campaigns()
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        folds = group_stratified_folds(ds.tikg, ds.labels, n_splits=10, seed=0)
    assert len(folds) == 10
    for f in folds:
        assert not (set(camp[f.train]) & set(camp[f.test]))
        assert not (set(camp[f.val]) & set(camp[f.test]))
