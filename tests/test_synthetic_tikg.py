def _fails(report):
    return {c.name for c in report.failures()}


# ---------------------------------------------------------------------------------------------- profiles / counts
def test_dev_profile_size_is_300_to_500_nodes(dev):
    assert 300 <= len(dev.nodes) <= 500
    assert validate(dev).ok, validate(dev).summary()


def test_manuscript_scale_exact_counts(scale):
    from collections import Counter
    assert Counter(n["type"] for n in scale.nodes) == MANUSCRIPT_COUNTS
    assert len(scale.nodes) == 3728 and len(scale.edges) == 11624
    assert len(scale.attack_paths) == 76
    rep = validate(scale)
    assert rep.ok, rep.summary()


def test_edge_relation_and_triplet_distribution(scale):
    from collections import Counter
    c = Counter(e["triplet"] for e in scale.edges)
    assert set(c) == {f"T{i}" for i in range(1, 12)}          # X1 extension not generated by default
    assert sum(c.values()) == 11624


def test_average_degree_matches_manuscript(scale):
    assert abs(2 * len(scale.edges) / len(scale.nodes) - 6.24) < 0.05


# ---------------------------------------------------------------------------------------------- determinism
def test_same_seed_reproduces_and_different_seed_differs():
    assert check_reproducible("dev", 42)
    a = dumps(generate("dev", 1).edges)
    b = dumps(generate("dev", 2).edges)
    assert a != b


def test_written_files_are_byte_identical_across_runs(tmp_path, dev):
    write_dataset(generate("dev", 42), tmp_path / "a")
    write_dataset(generate("dev", 42), tmp_path / "b")
    for f in ("nodes", "edges", "labels", "campaigns", "attack_paths", "metadata"):
        assert (tmp_path / "a" / f"{f}.json").read_bytes() == (tmp_path / "b" / f"{f}.json").read_bytes()


def test_roundtrip_and_metadata_flags(tmp_path, dev):
    out = write_dataset(dev, tmp_path / "d")
    meta = json.loads((out / "metadata.json").read_text())
    assert meta["dataset_type"] == "synthetic"
    assert meta["purpose"] == "development_and_pipeline_validation"
    assert meta["not_for_reported_experimental_results"] is True
    assert meta["seed"] == 42
    back = read_dataset(out)
    assert validate(back).ok


# ---------------------------------------------------------------------------------------------- semantic structure
def test_related_campaigns_share_more_than_unrelated(scale):
    sep = validate(scale).stats["similarity_separation"]
    assert sep["jaccard_related_campaigns"] > 5 * sep["jaccard_unrelated_campaigns"]
    assert sep["frac_related_campaign_pairs_sharing_vuln"] > 0.5 > sep["frac_unrelated_campaign_pairs_sharing_vuln"]


def test_edges_are_not_uniform_random(scale):
    loc = validate(scale).stats["edge_locality"]
    # uniform random edges over 60 campaigns would give ~1.7% in-campaign
    assert loc["campaign"] > 0.5 and loc["cross_family"] < 0.15


# ---------------------------------------------------------------------------------------------- synthetic realism / safety
def test_identifiers_are_clearly_synthetic(dev):
    for n in dev.nodes:
        assert n["attrs"]["synthetic"] is True
        if n["type"] == "vulnerability":
            m = re.fullmatch(r"CVE-(\d{4})-\d{5}", n["name"])
            assert m and 2090 <= int(m.group(1)) <= 2099
            assert 0.0 <= n["attrs"]["cvss_base_score"] <= 10.0
        if n["type"] == "attack_method":
            assert re.fullmatch(r"T1\d{3}(\.\d{3})?", n["attrs"]["technique_id"])
        if n["type"] == "file" and n["subtype"] == "domain":
            assert n["name"].endswith(".example")
        if n["type"] == "file" and n["subtype"] == "email":
            assert n["name"].endswith("@example.invalid")
        if n["type"] == "file" and n["subtype"] == "hash":
            assert re.fullmatch(r"[0-9a-f]{32}|[0-9a-f]{40}|[0-9a-f]{64}", n["name"])


def test_cvss_formula_and_stored_scores(dev):
    assert cvss31_base_score("CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:U/C:H/I:H/A:H") == 9.8
    assert cvss31_base_score("CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:C/C:H/I:H/A:H") == 10.0
    assert cvss31_base_score("CVSS:3.1/AV:L/AC:L/PR:L/UI:N/S:U/C:H/I:N/A:N") == 5.5
    for n in dev.nodes:
        if n["type"] == "vulnerability":
            assert cvss31_base_score(n["attrs"]["cvss_vector"]) == n["attrs"]["cvss_base_score"]


def test_templates_are_valid_table2_triplets():
    for specs in PATH_TEMPLATES.values():
        for s in specs:
            types, steps = parse_template(s)
            assert len(types) == len(steps) + 1


# ---------------------------------------------------------------------------------------------- validation catches corruption
def _mut(ds):
    return copy.deepcopy(ds)


def test_validation_detects_schema_violation(dev):
    d = _mut(dev)
    e = next(e for e in d.edges if e["triplet"] == "T1")
    e["relation"] = "enables"
    assert "every_edge_respects_schema_T1_T11" in _fails(validate(d))


def test_validation_detects_wrong_direction(dev):
    d = _mut(dev)
    e = next(e for e in d.edges if e["triplet"] == "T2")
    e["source"], e["target"] = e["target"], e["source"]
    assert "every_edge_respects_schema_T1_T11" in _fails(validate(d))


def test_validation_detects_dangling_and_duplicates(dev):
    d = _mut(dev)
    d.edges[0]["target"] = "nope"
    assert "no_dangling_edge_endpoints" in _fails(validate(d))
    d = _mut(dev)
    d.nodes.append(copy.deepcopy(d.nodes[0]))
    assert "no_duplicate_node_ids" in _fails(validate(d))
    d = _mut(dev)
    d.edges.append(copy.deepcopy(d.edges[0]))
    assert "no_duplicate_edges" in _fails(validate(d))


def test_validation_detects_bad_campaign_label_and_counts(dev):
    d = _mut(dev)
    d.nodes[0]["campaign"] = "camp-999"
    assert "campaign_ids_exist_for_all_nodes" in _fails(validate(d))
    d = _mut(dev)
    del d.labels["labels"][d.nodes[3]["id"]]
    assert "labels_exist_for_every_node" in _fails(validate(d))
    d = _mut(dev)
    d.nodes.pop()
    assert "node_counts_exact_by_type" in _fails(validate(d))


def test_validation_detects_bad_attack_paths(dev):
    d = _mut(dev)
    d.attack_paths[0]["steps"][0]["target"] = d.attack_paths[-1]["nodes"][-1]
    assert "attack_paths_use_only_existing_edges_and_valid_templates" in _fails(validate(d))
    d = _mut(dev)
    d.attack_paths.pop()
    assert "attack_path_length_distribution" in _fails(validate(d))
    d = _mut(dev)
    d.metadata["not_for_reported_experimental_results"] = False
    assert "metadata_synthetic_flags" in _fails(validate(d))


def test_attack_path_distribution_and_validity(scale):
    from collections import Counter
    c = Counter("2" if p["n_edges"] == 2 else "3" if p["n_edges"] == 3 else ">=4" for p in scale.attack_paths)
    assert c == {"2": 32, "3": 26, ">=4": 18}
    edges = {(e["source"], e["relation"], e["target"]) for e in scale.edges}
    for p in scale.attack_paths:
        assert all((s["source"], s["relation"], s["target"]) in edges for s in p["steps"])


